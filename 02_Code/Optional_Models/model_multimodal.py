def timestep_embedding(timesteps, dim, max_period=10000):
    half = dim // 2
    freqs = torch.exp(
        -math.log(max_period) * torch.arange(start=0, end=half, dtype=torch.float32) / half
    ).to(device=timesteps.device)
    args = timesteps[:, None].float() * freqs[None]
    embedding = torch.cat([torch.cos(args), torch.sin(args)], dim=-1)
    if dim % 2:
        embedding = torch.cat([embedding, torch.zeros_like(embedding[:, :1])], dim=-1)
    return embedding


def unpatchify(x, patch_size, h, channels=1):
    x = einops.rearrange(x, 'B (h) (p1 C) -> B C (h p1) ', h=h, p1=patch_size)
    return x


class Attention(nn.Module):
    def __init__(self, dim, num_heads=8, qkv_bias=False, qk_scale=None, attn_drop=0., proj_drop=0.):
        super().__init__()
        self.num_heads = num_heads
        head_dim = dim // num_heads
        self.scale = qk_scale or head_dim ** -0.5

        self.qkv = nn.Linear(dim, dim * 3, bias=qkv_bias)
        self.attn_drop = nn.Dropout(attn_drop)
        self.proj = nn.Linear(dim, dim)
        self.proj_drop = nn.Dropout(proj_drop)
        self.rotary_emb = RotaryEmbedding(dim = head_dim)
        
    def forward(self, x):
        B, L, C = x.shape

        qkv = self.qkv(x) #+ self.c_attn(x)
        
        if ATTENTION_MODE == 'flash':
            qkv = einops.rearrange(qkv, 'B L (K H D) -> K B H L D', K=3, H=self.num_heads).float()
            q, k, v = qkv[0], qkv[1], qkv[2]  # B H L D
            q = self.rotary_emb.rotate_queries_or_keys(q)
            k = self.rotary_emb.rotate_queries_or_keys(k)
            x = torch.nn.functional.scaled_dot_product_attention(q, k, v)
            x = einops.rearrange(x, 'B H L D -> B L (H D)')
        elif ATTENTION_MODE == 'xformers':
            qkv = einops.rearrange(qkv, 'B L (K H D) -> K B L H D', K=3, H=self.num_heads)
            q, k, v = qkv[0], qkv[1], qkv[2]  # B L H D
            x = xformers.ops.memory_efficient_attention(q, k, v)
            x = einops.rearrange(x, 'B L H D -> B L (H D)', H=self.num_heads)
        elif ATTENTION_MODE == 'math':
            qkv = einops.rearrange(qkv, 'B L (K H D) -> K B H L D', K=3, H=self.num_heads)
            q, k, v = qkv[0], qkv[1], qkv[2]  # B H L D
            attn = (q @ k.transpose(-2, -1)) * self.scale
            attn = attn.softmax(dim=-1)
            attn = self.attn_drop(attn)
            x = (attn @ v).transpose(1, 2).reshape(B, L, C)
        else:
            raise NotImplemented

        x = self.proj(x)
        x = self.proj_drop(x)
        return x


class Block(nn.Module):

    def __init__(self, dim, num_heads, mlp_ratio=4., qkv_bias=False, qk_scale=None,
                 act_layer=nn.GELU, norm_layer=nn.LayerNorm, skip=False, use_checkpoint=False, attn_drop=0.0, proj_drop=0.0):
        super().__init__()
        self.norm1 = norm_layer(dim)
        self.attn = Attention(
            dim, num_heads=num_heads, qkv_bias=qkv_bias, qk_scale=qk_scale, attn_drop=attn_drop, proj_drop=proj_drop)
        self.norm2 = norm_layer(dim)
        mlp_hidden_dim = int(dim * mlp_ratio)
        self.mlp = Mlp(in_features=dim, hidden_features=mlp_hidden_dim, act_layer=act_layer)
        self.skip_linear = nn.Linear(2 * dim, dim) if skip else None
        self.use_checkpoint = use_checkpoint

    def forward(self, x, skip=None):
        if self.use_checkpoint:
            return torch.utils.checkpoint.checkpoint(self._forward, x, skip)
        else:
            return self._forward(x, skip)

    def _forward(self, x, skip=None):
        if self.skip_linear is not None:
            x = self.skip_linear(torch.cat([x, skip], dim=-1))
        x = x + self.attn(self.norm1(x))
        x = x + self.mlp(self.norm2(x))
        return x


class PatchEmbed(nn.Module):
    """ Image to Patch Embedding
    """
    def __init__(self, patch_size, in_chans=1, embed_dim=768):
        super().__init__()
        self.patch_size = patch_size
        self.proj = nn.Conv1d(in_chans, embed_dim, kernel_size=patch_size, stride=patch_size)

    def forward(self, x):
        B, C, H= x.shape
        assert H % self.patch_size == 0
        x = self.proj(x).flatten(2).transpose(1, 2)
        return x



class UViT(nn.Module):
    def __init__(self, input_size=[2920, 2920], patch_size=[8,8], in_chans = 26, out_chans=1, embed_dim=256, depth=12, num_heads=8, mlp_ratio=4.,
                 qkv_bias=False, qk_scale=None, norm_layer=nn.LayerNorm, mlp_time_embed=False,
                 use_checkpoint=False, conv=True, skip=True, attn_drop=0.0, proj_drop=0.0, pred_drop=0.0 ,out_class = [2], cov_dim=0):
        
        super().__init__()
        self.num_features = self.embed_dim = embed_dim  # num_features for consistency with other models
        self.in_chans = in_chans
        self.out_chans = out_chans
        self.patch_size = patch_size   
        self.out_class = out_class
        self.cov_dim = cov_dim

        self.patch_embed = nn.ParameterList()
        self.num_patches = []
        for i in range(0, len(patch_size)):
            self.patch_embed.append( PatchEmbed(patch_size=patch_size[i], in_chans=in_chans, embed_dim=embed_dim)    )
           
            if input_size[i] % self.patch_size[i] == 0:
                self.num_patches.append( input_size[i] // self.patch_size[i]  )
            else:
                self.num_patches.append(  input_size[i] // self.patch_size[i] + 1  )
        
        self.in_blocks = nn.ModuleList([
            Block(dim=embed_dim, num_heads=num_heads, mlp_ratio=mlp_ratio, qkv_bias=qkv_bias, qk_scale=qk_scale,
                norm_layer=norm_layer, use_checkpoint=use_checkpoint, attn_drop=attn_drop,proj_drop=proj_drop)
            for _ in range(depth // 2)])

        self.mid_block = Block(dim=embed_dim, num_heads=num_heads, mlp_ratio=mlp_ratio, qkv_bias=qkv_bias, qk_scale=qk_scale,
                norm_layer=norm_layer, use_checkpoint=use_checkpoint, attn_drop=attn_drop,proj_drop=proj_drop)

        self.out_blocks = nn.ModuleList([
            Block(
                dim=embed_dim, num_heads=num_heads, mlp_ratio=mlp_ratio, qkv_bias=qkv_bias, qk_scale=qk_scale,
                norm_layer=norm_layer, skip=skip, use_checkpoint=use_checkpoint, attn_drop=attn_drop,proj_drop=proj_drop)
            for _ in range(depth // 2)])

        self.norm = norm_layer(embed_dim)
        self.drop_layer = nn.Dropout(p=pred_drop)
        self.norm1 = norm_layer(embed_dim)

        self.latent_pred = nn.ParameterList()
        for i in range(0, len(self.out_class)):
            self.latent_pred.append( nn.Linear(embed_dim, self.out_class[i], bias=True) )

        if self.cov_dim>0:
            self.cov_mapping = PatchEmbed(patch_size=1, in_chans=1, embed_dim=embed_dim)

        ###add cls
        self.cls_token = nn.Parameter(torch.zeros(1, len(self.out_class), embed_dim))

        self.apply(self._init_weights)

    def _init_weights(self, m):
        if isinstance(m, nn.Linear):
            trunc_normal_(m.weight, std=.02)
            if isinstance(m, nn.Linear) and m.bias is not None:
                nn.init.constant_(m.bias, 0)
        elif isinstance(m, nn.LayerNorm):
            nn.init.constant_(m.bias, 0)
            nn.init.constant_(m.weight, 1.0)


    @torch.jit.ignore
    def no_weight_decay(self):
        return {'pos_embed'}

    def process_x(self, x, process_fun, i):
        B, C, H = x.shape

        if H % self.patch_size[i] == 0:        
            x = process_fun(x)
            h = H // self.patch_size[i]
        else:
            num_of_zeros = self.patch_size[i] * (H // self.patch_size[i] + 1) - H
            pad_x = torch.zeros(B, C, num_of_zeros, device=x.device)
            x = torch.cat((x, pad_x), 2)
            h = x.shape[2] // self.patch_size[i]
            x = process_fun(x)     
        return x


    def forward(self, x, cov_feature=None):
        B, C, H = x[0].shape

        for i in range(0, len(x)):
            if i==0:
                x1 = self.process_x(x[i], self.patch_embed[i], i)
            else:
                x1 = torch.cat((x1 , self.process_x(x[i], self.patch_embed[i], i)), 1)

        if self.cov_dim>0:

            cov_feature1 = self.cov_mapping(cov_feature)
            x1= torch.cat((cov_feature1, x1), 1)

        cls_tokens = self.cls_token.expand(B, -1, -1)
        x = torch.cat((cls_tokens, x1),1) 

        skips = []
        for blk in self.in_blocks:
            x = blk(x)
            skips.append(x)

        x = self.mid_block(x)

        for blk in self.out_blocks:
            x = blk(x, skips.pop())

        cls_token = self.norm1(self.drop_layer(x[:,:len(self.out_class),:]))
        out = []
        for i in range(0, len(self.out_class)):
            out.append(self.latent_pred[i](cls_token[:,i,:]))
       
        return out